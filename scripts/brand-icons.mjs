// Regenerates apps/web/src/ui/brandIconData.ts from theSVG (https://thesvg.org,
// https://github.com/glincker/thesvg, MIT). Run with `node scripts/brand-icons.mjs`; it needs network.
// Each icon keeps the per-icon license theSVG's manifest gives it; see THIRD_PARTY_NOTICES.md.
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const COMMIT = '30e9b35f9d79919345a6586a31edcc3b47a37ff6'
const BASE = `https://raw.githubusercontent.com/glincker/thesvg/${COMMIT}`

// id: [theSVG slug, variant file, mono?]. Mono icons draw in the text colour.
const ICONS = {
  cursor: ['cursor', 'mono', true],
  vscode: ['visual-studio-code', 'default', false],
  vscodium: ['vscodium', 'default', false],
  windsurf: ['windsurf', 'mono', true],
  trae: ['trae', 'mono', true],
  kiro: ['kiro', 'default', false],
  zed: ['zed', 'light', true],
  jetbrains: ['jetbrains', 'mono', true],
  idea: ['intellij-idea', 'mono', true],
  webstorm: ['webstorm', 'default', true],
  pycharm: ['pycharm', 'mono', true],
  goland: ['goland', 'default', true],
  rider: ['rider', 'default', true],
  clion: ['clion', 'default', true],
  phpstorm: ['phpstorm', 'default', true],
  rubymine: ['rubymine', 'default', true],
  apple: ['apple', 'mono', true],
  windows: ['windows', 'default', false],
  claude: ['claude', 'default', false],
  codex: ['codex-openai', 'color', true],
  grok: ['grok', 'light', true],
  github: ['github', 'mono', true],
  git: ['git', 'default', false],
}

const get = async (url) => {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${url}: ${res.status}`)
  return res.text()
}

const manifest = JSON.parse(await get(`${BASE}/src/data/icons.json`))
const bySlug = new Map(manifest.map((icon) => [icon.slug, icon]))

const entries = []
for (const [id, [slug, variant, mono]] of Object.entries(ICONS)) {
  const meta = bySlug.get(slug)
  if (!meta) throw new Error(`theSVG has no ${slug}`)
  const file = meta.variants[variant] ?? `/icons/${slug}/${variant}.svg`
  const svg = await get(`${BASE}/public${file}`)
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1]
  if (!viewBox) throw new Error(`${slug}: no viewBox`)
  const rootFill = /<svg[^>]*\sfill="([^"]+)"/.exec(svg)?.[1]
  const rootRule = /<svg[^>]*\sfill-rule="([^"]+)"/.exec(svg)?.[1]
  let body = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/<title>[\s\S]*?<\/title>/g, '')
    .replace(/>\s+</g, '><')
    .replace(/\s+/g, ' ')
    .trim()
  // Ids get a per-instance prefix at render time, so two copies on a page never collide.
  body = body
    .replace(/\sid="([^"]+)"/g, ' id="__ID__$1"')
    .replace(/url\(#([^)]+)\)/g, 'url(#__ID__$1)')
  if (mono) body = body.replace(/fill="#(?:000|000000|0A0A0A|0a0a0a)"/g, 'fill="currentColor"')
  const fill = mono ? 'currentColor' : rootFill && rootFill !== 'none' ? rootFill : rootFill
  entries.push({
    id,
    slug,
    title: meta.title,
    license: meta.license,
    viewBox,
    fill,
    rule: rootRule,
    body,
  })
}

const out = [
  '// Generated by scripts/brand-icons.mjs from theSVG (https://thesvg.org,',
  `// github.com/glincker/thesvg@${COMMIT.slice(0, 12)}; MIT for the collection). Do not edit by hand.`,
  '// Logos are trademarks of their owners, used only to identify their products; per-icon',
  '// licenses are in THIRD_PARTY_NOTICES.md.',
  '',
  'export interface BrandIconData {',
  '  /** The theSVG slug and the license its manifest lists. */',
  '  slug: string',
  '  title: string',
  '  license: string',
  '  viewBox: string',
  '  fill?: string',
  '  fillRule?: string',
  '  /** Inner SVG markup; `__ID__` is replaced with a per-instance id prefix. */',
  '  body: string',
  '}',
  '',
  'export const BRAND_ICONS = {',
  ...entries.map(
    (e) =>
      `  ${e.id}: ${JSON.stringify({ slug: e.slug, title: e.title, license: e.license, viewBox: e.viewBox, ...(e.fill ? { fill: e.fill } : {}), ...(e.rule ? { fillRule: e.rule } : {}), body: e.body })},`,
  ),
  '} satisfies Record<string, BrandIconData>',
  '',
  'export type BrandId = keyof typeof BRAND_ICONS',
  '',
]
const target = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  '../apps/web/src/ui/brandIconData.ts',
)
writeFileSync(target, out.join('\n'))
for (const e of entries) console.log(`${e.id.padEnd(10)} ${e.slug.padEnd(20)} ${e.license}`)
