// Inlines xterm.js into one self-contained page that the Terminal pane loads in a WebView, so the
// terminal works without internet. Run it again after changing the xterm version or the page:
//   pnpm --filter @beddcode/mobile build:terminal
import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const require = createRequire(import.meta.url)
const read = (specifier) => readFileSync(require.resolve(specifier), 'utf8')

// A literal `</script` inside inlined code would end the tag early.
const safe = (code) => code.replace(/<\/script/gi, '<\\/script')

const page = readFileSync(join(here, 'terminal-page.html'), 'utf8')
  .replace('/*XTERM_CSS*/', () => read('@xterm/xterm/css/xterm.css'))
  .replace('/*XTERM_JS*/', () => safe(read('@xterm/xterm/lib/xterm.js')))
  .replace('/*FIT_JS*/', () => safe(read('@xterm/addon-fit/lib/addon-fit.js')))

const out = join(here, '..', 'src', 'features', 'terminal', 'terminalHtml.ts')
writeFileSync(
  out,
  `// Generated by scripts/build-terminal.mjs. Do not edit.\nexport const TERMINAL_HTML = ${JSON.stringify(page)}\n`,
)
console.log(`wrote ${out} (${(page.length / 1024).toFixed(0)} KB)`)
